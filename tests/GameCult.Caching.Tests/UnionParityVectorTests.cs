        private static UnionSurface Constructed() => Constructed(null);

        private static UnionSurface Constructed(Node? root) => new()
        {
            Id = "surface",
            Version = 3,
            Root = root ?? new Box
            {
                Id = "0000000000c0",
                Children =
                {
                    new Text { Id = "0000000000c1", Content = "hello" },
                    new Use
                    {
                        Id = "0000000000c2",
                        Composition = new Composition
                        {
                            Name = "comp",
                            Body = new Box { Id = "0000000000d0", Children = { new Text { Id = "0000000000d1", Content = "x" }, new Image { Id = "0000000000d2", Uri = "uri://a", Alt = "alt" } } }
                        },
                        Slots = { new Text { Id = "0000000000e1", Content = "slot" }, null!, new Box { Id = "0000000000e2" } }
                    },
                    new Image { Id = "0000000000c3", Uri = "uri://b", Alt = "" }
                }
            },
            Outcomes = { new Pending { Message = "wait", Id = "0000000000a1" }, new Completed { SourceVersion = 7, Id = "0000000000a2" }, new Denied { Id = "0000000000a3" } },
            Part = new Tool { Name = "hammer", Uses = 12 },
            Crafted = new Part { Name = "gear", Count = 4 },
            Missing = null
        };

        // A readable tree of a decoded value, for comparing what was read without re-encoding it.
        private static string Describe(object? value) => value switch
        {
            null => "nil",
            UnionSurface s => $"Surface({s.Id},{s.Version},{Describe(s.Root)},[{string.Join(";", s.Outcomes.Select(Describe))}],{Describe(s.Part)},{Describe(s.Crafted)},{Describe(s.Missing)})",
            Box b => $"Box({b.Id},[{string.Join(";", b.Children.Select(Describe))}])",
            Text t => $"Text({t.Id},{t.Content})",
            Use u => $"Use({u.Id},{Describe(u.Composition)},[{string.Join(";", u.Slots.Select(Describe))}])",
            Image i => $"Image({i.Id},{i.Uri},{i.Alt})",
            Composition c => $"Composition({c.Name},{Describe(c.Body)})",
            Pending p => $"Pending({p.Message})",
            Completed c => $"Completed({c.SourceVersion})",
            Denied => "Denied",
            Floor => "Floor",
            Ceiling => "Ceiling",
            Wrap w => $"Wrap({Describe(w.Inner)})",
            Gem g => $"Gem({g.Name})",
            Tool t => $"Tool({t.Name},{t.Uses})",
            Part p => $"Part({p.Name},{p.Count})",
            _ => throw new InvalidOperationException(value.GetType().Name)
        };

        // ---- the hand-written emitter: the expected bytes, written with MessagePackWriter, not captured from the code under test ----

        private delegate void Emit(ref MessagePackWriter writer);

        private static byte[] Raw(Emit emit)
        {
            var buffer = new ArrayBufferWriter<byte>();
            var writer = new MessagePackWriter(buffer);
            emit(ref writer);
            writer.Flush();
            return buffer.WrittenSpan.ToArray();
        }

        private static readonly Emit Nil = (ref MessagePackWriter w) => w.WriteNil();
        private static readonly Emit ExtraSlot = (ref MessagePackWriter w) => w.Write("extra-slot");

        private static Emit Str(string s) => (ref MessagePackWriter w) => w.Write(s);
        private static Emit Num(int n) => (ref MessagePackWriter w) => w.Write(n);

        private static Emit Slots(params Emit[] slots) => (ref MessagePackWriter w) =>
        {
            w.WriteArrayHeader(slots.Length);
            foreach (var slot in slots) slot(ref w);
        };

        private static Emit ArmOf(int key, params Emit[] slots) => (ref MessagePackWriter w) =>
        {
            w.WriteArrayHeader(2); w.Write(key);
            Slots(slots)(ref w);
        };

        // The slots, with one slot past the last declared key when extra.
        private static Emit Plus(bool extra, params Emit[] slots) => Slots(extra ? slots.Append(ExtraSlot).ToArray() : slots);

        private sealed record Extra(bool Record = false, bool Composition = false, bool RootArm = false, bool ListElement = false);

        private static Emit BoxArm(string id, Emit children, bool extra = false) => ArmOf(0, extra
            ? new[] { Str(id), children, ExtraSlot } : new[] { Str(id), children });

        private static Emit TextArm(string id, string content, bool extra = false) => ArmOf(1, extra
            ? new[] { Str(id), Str(content), ExtraSlot } : new[] { Str(id), Str(content) });

        private static Emit ImageArm(string id, string uri, string alt) => ArmOf(5, Str(id), Str(uri), Nil, Str(alt));

        // The constructed value's payload, with a part of the structure replaceable to build a refusal or an extra-slot case.
        private static byte[] Surface(Emit? root = null, Emit? outcomes = null, Emit? crafted = null, Extra? extra = null, Emit? trailing = null)
        {
            extra ??= new Extra();
            root ??= BoxArm("0000000000c0", Slots(
                TextArm("0000000000c1", "hello"),
                ArmOf(2, Str("0000000000c2"),
                    Plus(extra.Composition, Str("comp"), BoxArm("0000000000d0", Slots(TextArm("0000000000d1", "x"), ImageArm("0000000000d2", "uri://a", "alt")))),
                    Slots(TextArm("0000000000e1", "slot", extra.ListElement), Nil, BoxArm("0000000000e2", Slots()))),
                ImageArm("0000000000c3", "uri://b", "")), extra.RootArm);
            outcomes ??= Slots(ArmOf(0, Str("wait"), Str("0000000000a1")), ArmOf(1, Num(7), Str("0000000000a2")), ArmOf(2, Str("0000000000a3")));
            crafted ??= ArmOf(1, Str("gear"), Num(4));
            var slots = new[] { Str("surface"), Num(3), root, outcomes, ArmOf(1, Str("hammer"), Num(12)), crafted, Nil };
            return Raw(Slots(trailing != null ? slots.Append(trailing).ToArray() : extra.Record ? slots.Append(ExtraSlot).ToArray() : slots));
        }

        private static byte[] SerializeValue(UnionSurface value) => CultDocumentMessagePackSerialization.SerializeUntyped(value, typeof(UnionSurface), Registry);

        private static UnionSurface Decode(byte[] payload) =>
            (UnionSurface)CultDocumentMessagePackSerialization.DeserializeUntyped(typeof(UnionSurface), payload, Registry);

        // ---- the refusal and extra-slot vectors, each with its expected outcome as data ----

        // file, outcome ("refused" | "read-only" | "accepted"), union (logical name), arm key (null for none), detail.
        private sealed record Case(string File, string Outcome, string Union, int? Key, string Detail, byte[] Payload);

        private static IReadOnlyList<Case> Cases() => new[]
