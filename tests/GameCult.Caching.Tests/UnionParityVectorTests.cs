        };

        private static byte[] OutcomesFile() => Raw((ref MessagePackWriter w) =>
        {
            var cases = Cases();
            w.WriteArrayHeader(cases.Count);
            foreach (var c in cases)
            {
                w.WriteArrayHeader(5);
                w.Write(c.File); w.Write(c.Outcome); w.Write(c.Union);
                if (c.Key is { } key) w.Write(key); else w.WriteNil();
                w.Write(c.Detail);
            }
        });

        private static string UnionName(string logical) => logical switch
        {
            "Node" => typeof(Node).FullName!,
            "Outcome" => typeof(Outcome).FullName!,
            "CraftedItem" => typeof(CraftedItem).FullName!,
            "UnionSurface" => typeof(UnionSurface).FullName!,
            _ => throw new ArgumentOutOfRangeException(nameof(logical), logical, null)
        };

        private static string Chain(Exception exception)
        {
            var parts = new List<string>();
            for (var cause = exception; cause != null; cause = cause.InnerException) parts.Add(cause.Message);
            return string.Join(" <- ", parts);
        }

